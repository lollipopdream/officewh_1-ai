export type TranslationKey = keyof typeof TRANSLATIONS['ja'];

export function formatString(text: string, params?: Record<string, string | number>): string {
  if (!params) return text;
  return Object.entries(params).reduce((str, [key, val]) => {
    return str.replace(new RegExp(`\\{${key}\\}`, 'g'), String(val));
  }, text);
}

export function translate(key: TranslationKey | string, lang: Language = 'ja', params?: Record<string, string | number>): string {
  const langDict = TRANSLATIONS[lang] || TRANSLATIONS.ja;
  const raw = (langDict as Record<string, string>)[key] ?? (TRANSLATIONS.ja as Record<string, string>)[key] ?? key;
  return formatString(raw, params);
}

export function useT() {
  const language = useStore((s) => s.language);
  const t = (key: TranslationKey | string, params?: Record<string, string | number>) => {
    return translate(key, language, params);
  };
  return { t, language };
}
